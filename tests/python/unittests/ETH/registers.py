"""Word addresses and bit positions of the Ethernet MAC registers."""

CTRL = 0x00
STATUS = 0x01
IRQ_STATUS = 0x02
IRQ_ENABLE = 0x03
MAC_LO = 0x04
MAC_HI = 0x05
TX_LEN = 0x06
TX_CMD = 0x07
TX_DATA = 0x08
RX_LEN = 0x09
RX_DATA = 0x0A
RX_CMD = 0x0B
MDIO_CMD = 0x0C
MDIO_DATA = 0x0D
CNT_TX = 0x10
CNT_RX = 0x11
CNT_CRC = 0x12
CNT_PHY = 0x13
CNT_DROP = 0x14
CNT_FILTER = 0x15

CTRL_ENABLE = 1 << 0
CTRL_PROMISCUOUS = 1 << 1
CTRL_BROADCAST = 1 << 2
CTRL_MULTICAST = 1 << 3
CTRL_ACCEPT_ERRORS = 1 << 4
CTRL_SOFT_RESET = 1 << 5
CTRL_PHY_RESET = 1 << 6

STATUS_TX_BUSY = 1 << 0
STATUS_RX_READY = 1 << 1
STATUS_MDIO_BUSY = 1 << 2
STATUS_PHY_INT = 1 << 3
STATUS_MDIO_NOACK = 1 << 4

IRQ_RX_FRAME = 1 << 0
IRQ_TX_DONE = 1 << 1
IRQ_ERROR = 1 << 2
IRQ_MDIO_DONE = 1 << 3
IRQ_PHY = 1 << 4

TX_START = 1 << 0
TX_RESET_POINTER = 1 << 1
RX_RELEASE = 1 << 0
RX_REWIND = 1 << 1

SPEED = 0x0E

SPEED_MODE_AUTO = 0
SPEED_MODE_10 = 1
SPEED_MODE_100 = 2
SPEED_MODE_1000 = 3
SPEED_MODE_MASK = 0x3
SPEED_ACTIVE_SHIFT = 4
SPEED_ACTIVE_MASK = 0x3
SPEED_LINK = 1 << 8
SPEED_FULL_DUPLEX = 1 << 9
SPEED_RESOLVED = 1 << 10

PHY_STATUS_REG = 17
PHY_STATUS_LINK = 1 << 10
PHY_STATUS_RESOLVED = 1 << 11
PHY_STATUS_DUPLEX = 1 << 13
PHY_STATUS_SPEED_SHIFT = 14
